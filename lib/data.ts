export function findNewsItemBySlug(slug: string): NewsItem | null {
  const data = getNewsData();
  const allItems = [
    ...data.banner,
    ...data.sections.ai,
    ...data.sections.sand,
    ...data.sections.casting,
    ...data.sections.b2b,
    ...data.sections.world,
    ...data.sections.mfg,
  ];
  // Direct ID match (slug might just be the ID like "ai-001")
  const directMatch = allItems.find(item => item.id === slug);
  if (directMatch) return directMatch;

  // Extract ID from slug - look for known ID pattern at end
  const idMatch = slug.match(/([a-z]+-\d+)$/i);
  if (idMatch) {
    return allItems.find(item => item.id === idMatch[1]) || null;
  }

  return null;
}

export function slugify(item: NewsItem): string {
  const base = item.title
    .toLowerCase()
    .replace(/[^a-z0-9一-龥]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .substring(0, 50);
  return `${base}-${item.id}`;
}

